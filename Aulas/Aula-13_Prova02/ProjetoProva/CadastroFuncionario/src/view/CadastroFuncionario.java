    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        if ("".equals(txtNome.getText())) {
            JOptionPane.showMessageDialog(null, "Você deve digitar um nome antes de salvar!", "Alerta", JOptionPane.OK_OPTION);
        }
        else if (!rdoFeminino.isSelected() && !rdoMasculino.isSelected() && !rdoOutro.isSelected()) {
            JOptionPane.showMessageDialog(null, "Você deve selecionar um genero antes de salvar!", "Alerta", JOptionPane.OK_OPTION);
        }
        else if (cmbCargo.getSelectedItem() == "-----") {
            JOptionPane.showMessageDialog(null, "Você deve selecionar um idioma antes de salvar!", "Alerta", JOptionPane.OK_OPTION);
        }
        else {
            if (rdoMasculino.isSelected()) {
                genero = "masculino";
            }
            else if (rdoFeminino.isSelected()) {
                genero = "feminino";
            }
            else {
                genero = "outro";
            }
            
            rodar(txtNome.getText(), Integer.parseInt(
                    txtIdade.getText()), genero,cmbCargo.getSelectedItem().toString(), Double.parseDouble(
                    txtSalario.getText()));
            
            JOptionPane.showMessageDialog(null, "Pessoa adicionada com sucesso!", "Alerta", JOptionPane.OK_OPTION);
            
            limparCampos();
        }
    }//GEN-LAST:event_btnInserirActionPerformed

