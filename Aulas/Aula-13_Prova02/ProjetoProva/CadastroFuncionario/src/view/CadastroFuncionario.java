    public void rodar(String nome, int idade, String genero, String cargo, double salario) {

        Conexao c = new Conexao();
        c.getConexao();

        Funcionario f = new Funcionario();
        f.setNome(nome);
        f.setIdade(idade);
        f.setGenero(genero);
        f.setCargo(cargo);
        f.setSalario(salario);

        FuncionarioDAO fdao = new FuncionarioDAO();
        fdao.inserir(f);
    }
    
