    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        int idPessoa = Integer.parseInt(txtId.getText());
        PessoaDAO pDAO = new PessoaDAO();
        
        Pessoa p = pDAO.getPessoa(idPessoa);
        
        if (p == null) {
            limparFormulario();
            JOptionPane.showMessageDialog(null, "Pessoa não encontrada!", "Confirmação", JOptionPane.OK_OPTION);
        }
        else {
            txtIdInfo.setText(txtId.getText());
            txtNome.setText(p.getNome());
            
            if (p.getSexo().equals("M")) {
                RdoMasculino.setSelected(true);
            }
            else if (p.getSexo().equals("F")){
                RdoFeminino.setSelected(true);
            }
            
            cmbIdioma.setSelectedItem(p.getIdioma());
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

