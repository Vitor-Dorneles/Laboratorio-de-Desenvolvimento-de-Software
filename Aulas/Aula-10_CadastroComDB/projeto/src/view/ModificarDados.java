    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        Pessoa p = new Pessoa();
        p.setId(Integer.parseInt(txtIdInfo.getText()));
        p.setNome(txtNome.getText());
        if (RdoMasculino.isSelected()) {
            p.setSexo("M");
        }
        else if (RdoFeminino.isSelected()){
            p.setSexo("F");
        }
        p.setIdioma(cmbIdioma.getSelectedItem().toString());
        
        PessoaDAO pDAO = new PessoaDAO();
        pDAO.editar(p);
        limparFormulario();
        
        JOptionPane.showMessageDialog(null, "Pessoa atualizada!", "Confirmação", JOptionPane.OK_OPTION);
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir?", "Exclusão",  JOptionPane.YES_NO_OPTION);
        
        if (resposta == JOptionPane.YES_OPTION) {
            PessoaDAO pDAO = new PessoaDAO();
            pDAO.excluir(Integer.parseInt(txtIdInfo.getText()));
            limparFormulario();
            
            JOptionPane.showMessageDialog(null, "Pessoa excluida!", "Confirmação", JOptionPane.OK_OPTION);
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

